# CLI: --no-llm wires through to apply; n_arbitrated surfaced in output
# --------------------------------------------------------------------------- #
class TestCLI:
    """The apply CLI command wires --no-llm and surfaces n_arbitrated."""

    def test_apply_no_llm_flag_suppresses_arbitration(
        self, new_photos: Path, settings: Settings, learned_profile: str, monkeypatch
    ):
        """CLI apply --no-llm: n_arbitrated == 0 in returned report."""
        from unittest.mock import patch

        import typer
        from typer.testing import CliRunner

        from photovault.cli.main import app

        runner = CliRunner()
        # Patch get_settings so the profile dir is the test one.
        with patch("photovault.cli.main.get_settings", return_value=settings):
            result = runner.invoke(
                app,
                ["apply", str(new_photos), "--name", learned_profile, "--no-llm", "--no-report"],
            )
        assert result.exit_code == 0
        # When --no-llm is active: either "arbitrated: 0" or no arbitration line,
        # but the command must succeed without error.

    def test_apply_shows_n_arbitrated_in_output(
        self, new_photos: Path, settings: Settings, learned_profile: str
    ):
        """CLI apply surfaces n_arbitrated in printed summary (value >= 0)."""
        from unittest.mock import patch

        from typer.testing import CliRunner

        from photovault.cli.main import app

        runner = CliRunner()
        with patch("photovault.cli.main.get_settings", return_value=settings):
            result = runner.invoke(
                app,
                ["apply", str(new_photos), "--name", learned_profile, "--no-llm", "--no-report"],
            )
        assert result.exit_code == 0
        # The output should include the arbitrated count.
        assert "arbitrated" in result.output.lower()
