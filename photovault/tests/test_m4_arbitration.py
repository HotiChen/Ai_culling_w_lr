# Stage-A: injectable judge in learn_from_folder
# --------------------------------------------------------------------------- #
class TestStageA:
    """learn_from_folder wires the injected judge into profile.md generation."""

    def test_fake_judge_text_lands_in_profile_md(
        self, catalog_folder: Path, settings: Settings
    ):
        """When a FakeJudge is injected, its output is written to profile.md."""
        from photovault.core.learn import learn_from_folder
        from photovault.core.profile import load_profile

        fake = FakeJudge()
        settings.llm.enabled = True  # must be enabled for judge to be called

        report = learn_from_folder(
            catalog_folder, "proftest", settings, use_llm=True, judge=fake
        )

        assert report.llm_used is True
        prof = load_profile(settings.profiles_dir, "proftest")
        assert prof.profile_md is not None
        # FakeJudge.write_profile returns text containing the profile name.
        assert "proftest" in prof.profile_md
        assert "FakeJudge" in prof.profile_md

    def test_injected_judge_write_profile_called_with_name_and_stats(
        self, catalog_folder: Path, settings: Settings
    ):
        """The injected judge's write_profile is called with the profile name + stats."""
        from photovault.core.learn import learn_from_folder

        fake = FakeJudge()
        settings.llm.enabled = True

        learn_from_folder(
            catalog_folder, "check_args", settings, use_llm=True, judge=fake
        )

        assert len(fake.write_profile_calls) == 1
        called_name, called_stats = fake.write_profile_calls[0]
        assert called_name == "check_args"
        assert isinstance(called_stats, dict)
        assert "keep_rate" in called_stats or len(called_stats) > 0

    def test_unavailable_judge_writes_placeholder_and_sets_llm_used_false(
        self, catalog_folder: Path, settings: Settings
    ):
        """When an injected judge raises JudgeUnavailable, placeholder is written."""
        from photovault.core.learn import learn_from_folder
        from photovault.core.profile import load_profile

        settings.llm.enabled = True

        report = learn_from_folder(
            catalog_folder,
            "unavail_test",
            settings,
            use_llm=True,
            judge=UnavailableJudge(),
        )

        assert report.llm_used is False
        assert "unavailable" in report.llm_note.lower()

        prof = load_profile(settings.profiles_dir, "unavail_test")
        # The placeholder contains boilerplate text (not FakeJudge's output).
        assert prof.profile_md is not None
        assert "placeholder" in prof.profile_md.lower() or "Taste Profile" in prof.profile_md

    def test_judge_not_called_when_use_llm_false(
        self, catalog_folder: Path, settings: Settings
    ):
        """When use_llm=False, the injected judge's write_profile is never called."""
        from photovault.core.learn import learn_from_folder

        fake = FakeJudge()
        settings.llm.enabled = True

        learn_from_folder(
            catalog_folder, "nollm", settings, use_llm=False, judge=fake
        )

        assert len(fake.write_profile_calls) == 0

    def test_judge_not_called_when_llm_disabled_in_settings(
        self, catalog_folder: Path, settings: Settings
    ):
        """When settings.llm.enabled=False, the injected judge is not used."""
        from photovault.core.learn import learn_from_folder

        fake = FakeJudge()
        settings.llm.enabled = False  # disabled via settings

        learn_from_folder(
            catalog_folder, "disabled", settings, use_llm=True, judge=fake
        )

        assert len(fake.write_profile_calls) == 0

    def test_existing_signature_preserved_no_judge(
        self, catalog_folder: Path, settings: Settings
    ):
        """Without judge, the existing behavior (use_llm=False) stays intact."""
        from photovault.core.learn import learn_from_folder
        from photovault.core.profile import load_profile

        report = learn_from_folder(
            catalog_folder, "nojudge", settings, use_llm=False
        )

        assert report.llm_used is False
        prof = load_profile(settings.profiles_dir, "nojudge")
        # Placeholder profile.md is always written.
        assert prof.profile_md is not None


